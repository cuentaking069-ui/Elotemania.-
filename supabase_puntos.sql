create table if not exists public.movimientos_puntos (
  id bigint generated by default as identity primary key,
  cliente_id bigint not null references public.clientes(id),
  tipo text not null check (tipo in ('compra','canje')),
  puntos integer not null check (puntos > 0),
  venta_id bigint null references public.ventas(id),
  descripcion text,
  creado_en timestamptz not null default now(),
  usuario_id bigint null references public.usuarios(id)
);

create index if not exists movimientos_puntos_cliente_fecha_idx
  on public.movimientos_puntos(cliente_id, creado_en desc);

alter table public.movimientos_puntos enable row level security;
revoke all on public.movimientos_puntos from anon, authenticated;
grant all on public.movimientos_puntos to service_role;

create or replace function public.registrar_venta_punto(
  p_nombre text,
  p_whatsapp text,
  p_total numeric,
  p_usuario_id bigint
)
returns table(venta_id bigint, nombre text, puntos integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cliente_id bigint;
  v_venta_id bigint;
  v_puntos integer;
begin
  if coalesce(trim(p_nombre),'') = '' or coalesce(trim(p_whatsapp),'') = '' or p_total is null or p_total <= 0 then
    raise exception 'Datos de venta no válidos';
  end if;

  insert into public.clientes(nombre, whatsapp, puntos, premios_obtenidos)
  values (trim(p_nombre), regexp_replace(p_whatsapp, '\D', '', 'g'), 1, 0)
  on conflict (whatsapp) do update
    set nombre = excluded.nombre,
        puntos = public.clientes.puntos + 1
  returning id, clientes.puntos into v_cliente_id, v_puntos;

  insert into public.ventas(cliente_id, total, puntos_ganados)
  values (v_cliente_id, p_total, 1)
  returning id into v_venta_id;

  insert into public.movimientos_puntos(cliente_id,tipo,puntos,venta_id,descripcion,usuario_id)
  values (v_cliente_id,'compra',1,v_venta_id,'Punto por compra confirmada',p_usuario_id);

  return query
    select v_venta_id, c.nombre, c.puntos
    from public.clientes c where c.id = v_cliente_id;
end;
$$;

create or replace function public.canjear_premio_puntos(p_whatsapp text)
returns table(nombre text, puntos integer, premios_obtenidos integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_cliente_id bigint;
begin
  select c.id into v_cliente_id
  from public.clientes c
  where c.whatsapp = regexp_replace(p_whatsapp, '\D', '', 'g')
  for update;

  if v_cliente_id is null then
    raise exception 'No existe un cliente con ese WhatsApp';
  end if;

  update public.clientes
  set puntos = puntos - 10,
      premios_obtenidos = premios_obtenidos + 1
  where id = v_cliente_id and puntos >= 10;

  if not found then
    raise exception 'Se necesitan 10 puntos para canjear el elote gratis';
  end if;

  insert into public.movimientos_puntos(cliente_id,tipo,puntos,descripcion)
  values (v_cliente_id,'canje',10,'Canje de 1 elote gratis');

  return query
    select c.nombre,c.puntos,c.premios_obtenidos
    from public.clientes c where c.id = v_cliente_id;
end;
$$;

revoke all on function public.registrar_venta_punto(text,text,numeric,bigint) from public, anon, authenticated;
revoke all on function public.canjear_premio_puntos(text) from public, anon, authenticated;
grant execute on function public.registrar_venta_punto(text,text,numeric,bigint) to service_role;
grant execute on function public.canjear_premio_puntos(text) to service_role;
